namespace VedaTax.Api.Services;

public class StorageOptions
{
    /// <summary>Folder for uploaded documents; relative paths are resolved against the app's content root.</summary>
    public string UploadsPath { get; set; } = "App_Data/uploads";
    public long MaxFileBytes { get; set; } = 15 * 1024 * 1024;
}

/// <summary>Stores portal documents on local disk under {UploadsPath}/{filingId}/{random name}.</summary>
public class FileStorage(Microsoft.Extensions.Options.IOptions<StorageOptions> options, IWebHostEnvironment env)
{
    public static readonly HashSet<string> AllowedExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".pdf", ".jpg", ".jpeg", ".png", ".heic", ".doc", ".docx", ".xls", ".xlsx", ".csv", ".txt", ".zip"
    };

    private readonly StorageOptions _opt = options.Value;

    public long MaxFileBytes => _opt.MaxFileBytes;

    private string Root => Path.IsPathRooted(_opt.UploadsPath)
        ? _opt.UploadsPath
        : Path.Combine(env.ContentRootPath, _opt.UploadsPath);

    public async Task<string> SaveAsync(int filingId, IFormFile file, CancellationToken ct)
    {
        var ext = Path.GetExtension(file.FileName).ToLowerInvariant();
        var stored = $"{Guid.NewGuid():N}{ext}";
        var dir = Path.Combine(Root, filingId.ToString());
        Directory.CreateDirectory(dir);
        await using var fs = File.Create(Path.Combine(dir, stored));
        await file.CopyToAsync(fs, ct);
        return stored;
    }

    public string? PathFor(int filingId, string storedName)
    {
        // storedName is generated by us, but guard against path tricks anyway.
        if (storedName.Contains('/') || storedName.Contains('\\') || storedName.Contains("..")) return null;
        var p = Path.Combine(Root, filingId.ToString(), storedName);
        return File.Exists(p) ? p : null;
    }

    public void Delete(int filingId, string storedName)
    {
        var p = PathFor(filingId, storedName);
        if (p is not null) File.Delete(p);
    }
}
